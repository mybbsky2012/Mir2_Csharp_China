	public static Packet ReceivePacket(byte[] rawBytes, out byte[] extra)
	{
		extra = rawBytes;
		if (rawBytes.Length < 4)
		{
			return null;
		}
		int num = (rawBytes[1] << 8) + rawBytes[0];
		if (num > rawBytes.Length || num < 2)
		{
			return null;
		}
		Packet packet;
		using (MemoryStream input = new MemoryStream(rawBytes, 2, num - 2))
		{
			using BinaryReader binaryReader = new BinaryReader(input);
			try
			{
				short index = binaryReader.ReadInt16();
				packet = (IsServer ? GetClientPacket(index) : GetServerPacket(index));
				if (packet == null)
				{
					extra = new byte[0];
					return null;
				}
				packet.ReadPacket(binaryReader);
			}
			catch
			{
				throw new InvalidDataException();
			}
		}
		extra = new byte[rawBytes.Length - num];
		Buffer.BlockCopy(rawBytes, num, extra, 0, rawBytes.Length - num);
		return packet;
	}

	public IEnumerable<byte> GetPacketBytes()
	{
		if (Index < 0)
		{
			return new byte[0];
		}
		using MemoryStream memoryStream = new MemoryStream();
		memoryStream.SetLength(2L);
		memoryStream.Seek(2L, SeekOrigin.Begin);
		using BinaryWriter binaryWriter = new BinaryWriter(memoryStream);
		binaryWriter.Write(Index);
		WritePacket(binaryWriter);
		memoryStream.Seek(0L, SeekOrigin.Begin);
		binaryWriter.Write((short)memoryStream.Length);
		memoryStream.Seek(0L, SeekOrigin.Begin);
		byte[] array = new byte[memoryStream.Length];
		memoryStream.Read(array, 0, array.Length);
		return array;
	}

	protected abstract void ReadPacket(BinaryReader reader);

	protected abstract void WritePacket(BinaryWriter writer);

